#!/bin/sh
# Renders the Homebrew formula for a published release from its SHA256SUMS.
# Usage: packaging/homebrew/render-formula.sh vX.Y.Z SHA256SUMS > aftergreen.rb
# The output goes to Formula/aftergreen.rb in github.com/foldnine/homebrew-tap.
# Homebrew checks each archive against the sha256 in the formula on install.
set -eu
tag="${1:?usage: render-formula.sh vX.Y.Z SHA256SUMS}"
sums="${2:?usage: render-formula.sh vX.Y.Z SHA256SUMS}"
printf '%s\n' "$tag" | grep -Eq '^v[0-9]+\.[0-9]+\.[0-9]+$' || { echo "bad tag: $tag" >&2; exit 2; }

sum() {
	f="aftergreen_${tag}_$1.tar.gz"
	s="$(awk -v f="$f" '$2 == f {print $1}' "$sums")"
	printf '%s\n' "$s" | grep -Eq '^[0-9a-f]{64}$' || { echo "no checksum for $f in $sums" >&2; exit 1; }
	printf '%s' "$s"
}
base="https://github.com/foldnine/aftergreen/releases/download/${tag}"

cat <<RUBY
# Generated by packaging/homebrew/render-formula.sh from the ${tag} SHA256SUMS
# in github.com/foldnine/aftergreen. Do not edit by hand.
class Aftergreen < Formula
  desc "Post-deployment verification: VERIFIED, FAILED or UNKNOWN"
  homepage "https://aftergreen.foldnine.dev"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "${base}/aftergreen_${tag}_darwin_arm64.tar.gz"
      sha256 "$(sum darwin_arm64)"
    end
    on_intel do
      url "${base}/aftergreen_${tag}_darwin_amd64.tar.gz"
      sha256 "$(sum darwin_amd64)"
    end
  end

  on_linux do
    on_arm do
      url "${base}/aftergreen_${tag}_linux_arm64.tar.gz"
      sha256 "$(sum linux_arm64)"
    end
    on_intel do
      url "${base}/aftergreen_${tag}_linux_amd64.tar.gz"
      sha256 "$(sum linux_amd64)"
    end
  end

  def install
    bin.install "aftergreen"
  end

  test do
    assert_equal "aftergreen v#{version}", shell_output("#{bin}/aftergreen version").strip
    # Invalid input exits 2 without any network access.
    shell_output("#{bin}/aftergreen http --url not-a-url", 2)
  end
end
RUBY
